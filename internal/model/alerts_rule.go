package model

import "time"

// AlertRule представляет конфигурационное правило мониторинга организации
// Правило задаёт условие и порог срабатывания для транспортных средств компании
type AlertRule struct {
	ID             int           // Уникальный идентификатор правила
	OrganizationID int           // Идентификатор организации-владельца правила
	Type           AlertRuleType // Тип отслеживаемого нарушения (скорость, оффлайн, топливо)
	Name           string        // Человекочитаемое название правила для диспетчеров
	Threshold      float64       // Пороговое значение срабатывания
	Severity       SeverityLevel // Уровень критичности формируемого алерта
	Enabled        bool          // Флаг активности правила
	CreatedAt      time.Time     // Время создания правила
	UpdatedAt      *time.Time    // Время последнего изменения конфигурации
}
